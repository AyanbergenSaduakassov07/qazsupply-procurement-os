"""Generate THIRD_PARTY_NOTICES.md from what actually ships.

Shipped = production JS dependencies of every workspace package (`pnpm licenses list -r --prod`)
plus the non-dev Python dependencies (`uv export --no-dev`), with licences from pip-licenses.
Dev tooling (linters, test runners) is not distributed and is not listed.

Usage:
  uv run python scripts/notices.py          # rewrite THIRD_PARTY_NOTICES.md
  uv run python scripts/notices.py --check  # exit 1 if the file is stale
"""

import json
import logging
import re
import subprocess  # noqa: S404 - fixed argv, no shell
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import cast

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "THIRD_PARTY_NOTICES.md"
log = logging.getLogger("notices")


@dataclass(frozen=True, order=True)
class Notice:
    ecosystem: str
    name: str
    version: str
    licence: str
    url: str


def _run(argv: list[str]) -> str:
    return subprocess.run(argv, check=True, capture_output=True, text=True, cwd=ROOT).stdout  # noqa: S603


def npm_notices(listing: dict[str, list[dict[str, object]]]) -> list[Notice]:
    out = []
    for licence, pkgs in listing.items():
        for p in pkgs:
            if str(p["name"]).startswith("@qazsupply/"):
                continue  # our own workspace packages
            versions = cast("list[str]", p.get("versions") or [""])
            out += [
                Notice("npm", str(p["name"]), str(v), licence, str(p.get("homepage") or ""))
                for v in versions
            ]
    return out


def shipped_python(requirements: str) -> set[str]:
    """Package names from `uv export` output (drops comments, hashes and the editable root)."""
    names = set()
    for line in requirements.splitlines():
        m = re.match(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==", line)
        if m:
            names.add(_canon(m.group(1)))
    return names


def py_notices(licences: list[dict[str, str]], shipped: set[str]) -> list[Notice]:
    return [
        Notice("PyPI", p["Name"], p["Version"], p["License"], p.get("URL", ""))
        for p in licences
        if _canon(p["Name"]) in shipped
    ]


def _canon(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def render(notices: list[Notice]) -> str:
    lines = [
        "# Third-party notices",
        "",
        "QazSupply ships the open-source packages below. Each remains under its own licence; full",
        "licence texts are in each package's distribution. Generated by `scripts/notices.py`",
        "(do not edit by hand). Policy: `docs/compliance/third-party-licenses.md`.",
        "Vendored source (`vendor/`) keeps its own LICENSE file next to the code.",
        "",
        "| Ecosystem | Package | Version | Licence | Homepage |",
        "|---|---|---|---|---|",
    ]
    lines += [
        f"| {n.ecosystem} | {n.name} | {n.version} | {n.licence} | {n.url} |"
        for n in sorted(set(notices))
    ]
    return "\n".join(lines) + "\n"


def build() -> str:
    npm = json.loads(_run(["pnpm", "licenses", "list", "--json", "--prod", "-r"]))
    py = json.loads(_run(["uv", "run", "pip-licenses", "--format=json", "--with-urls"]))
    req = _run(["uv", "export", "--no-dev", "--no-hashes", "--format", "requirements-txt"])
    notices = npm_notices(npm) + py_notices(py, shipped_python(req))
    if not any(n.ecosystem == "npm" for n in notices):
        raise RuntimeError("no npm packages found: is node_modules installed?")
    return render(notices)


def main(argv: list[str]) -> int:
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    text = build()
    if "--check" in argv:
        if OUT.read_text() != text:
            log.error("THIRD_PARTY_NOTICES.md is stale: run `uv run python scripts/notices.py`")
            return 1
        return 0
    OUT.write_text(text)
    log.info("wrote %s", OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
