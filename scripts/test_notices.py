from scripts.notices import Notice, npm_notices, py_notices, render, shipped_python

REQ = """# This file was autogenerated by uv
-e .
fastapi==0.142.4
psycopg-binary==3.3.6 ; implementation_name != 'pypy'
    # via psycopg
typing_extensions==4.16.0
"""


def test_only_shipped_python_packages_are_listed() -> None:
    licences = [
        {"Name": "fastapi", "Version": "0.142.4", "License": "MIT", "URL": "u"},
        {"Name": "psycopg-binary", "Version": "3.3.6", "License": "LGPL-3.0", "URL": "u"},
        {"Name": "typing_extensions", "Version": "4.16.0", "License": "PSF-2.0", "URL": "u"},
        {"Name": "ruff", "Version": "1.0", "License": "MIT", "URL": "u"},  # dev tool
    ]
    names = {n.name for n in py_notices(licences, shipped_python(REQ))}
    assert names == {"fastapi", "psycopg-binary", "typing_extensions"}


def test_npm_listing_expands_every_version() -> None:
    listing: dict[str, list[dict[str, object]]] = {
        "MIT": [{"name": "a", "versions": ["1.0.0", "2.0.0"], "homepage": "h"}]
    }
    assert [n.version for n in npm_notices(listing)] == ["1.0.0", "2.0.0"]


def test_render_is_sorted_and_deduplicated() -> None:
    b = Notice("npm", "b", "1", "MIT", "")
    a = Notice("PyPI", "a", "1", "MIT", "")
    text = render([b, a, b])
    rows = [line for line in text.splitlines() if line.startswith("| npm") or "| PyPI" in line]
    assert rows == ["| PyPI | a | 1 | MIT |  |", "| npm | b | 1 | MIT |  |"]
