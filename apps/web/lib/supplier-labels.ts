const group = (locale: Locale, prefix: string, keys: readonly string[]) =>
  Object.fromEntries(keys.map((k) => [k, t(locale, `s360.${prefix}.${k}` as MessageKey)]));

export function supplierLabels(locale: Locale) {
  return {
    ...(Object.fromEntries(KEYS.map((k) => [k, t(locale, `s360.${k}` as MessageKey)])) as Record<
      (typeof KEYS)[number],
      string
    >),
    verdict: group(locale, "verdict", VERDICTS),
    factor: group(locale, "factor", FACTORS),
    tab: group(locale, "tab", ["ownership", "legal", "screening", "spend", "score"]),
    roleName: group(locale, "role", ["shareholder", "beneficial_owner", "director"]),
    kind: group(locale, "kind", ["company", "person"]),
    statusName: group(locale, "status", ["active", "liquidated"]),
    list: group(locale, "list", ["opensanctions", "goszakup_rnu", "dualuse"]),
    reason: group(locale, "reason", [...REASONS.confirmed, ...REASONS.dismissed]),
    degraded: group(locale, "degraded", ["down", "rate_limited", "schema_drift", "not_found"]),
    error: t(locale, "common.error"),
    drawer: findingsLabels(locale).drawer,
    openEvidence: findingsLabels(locale).openEvidence,
  };
}
export type SupplierLabels = ReturnType<typeof supplierLabels>;
